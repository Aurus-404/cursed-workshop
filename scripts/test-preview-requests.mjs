import assert from 'node:assert/strict';
import {latestTask} from '../frontend/latest-task.js';
import {localRequest} from '../frontend/local-request.js';
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let calls=[];
const latest=latestTask(async(signal,value)=>{calls.push(value);return value;},20);
const first=latest.run(1).catch(e=>e.name),second=latest.run(2).catch(e=>e.name),third=latest.run(3);
assert.deepEqual(await Promise.all([first,second,third]),['AbortError','AbortError',3]);
assert.deepEqual(calls,[3]);
let aborted=false;
const running=latestTask((signal,value)=>new Promise(resolve=>{signal.addEventListener('abort',()=>{aborted=true;resolve(value);});}),0);
const old=running.run(1).catch(e=>e.name);await sleep(10);running.cancel();assert.equal(await old,'AbortError');assert.ok(aborted);
let fetches=0;
globalThis.fetch=async()=>{fetches++;if(fetches===1)throw new TypeError('Failed to fetch');return {ok:true,json:async()=>({done:true})};};
assert.deepEqual(await localRequest('/api/job?id=private',undefined,'private-token'),{done:true});assert.equal(fetches,2);
globalThis.fetch=async()=>{fetches++;throw new TypeError('Failed to fetch');};fetches=0;
await assert.rejects(()=>localRequest('/api/generate',{name:'private'},'private-token'),/POST \/api\/generate/);
assert.equal(fetches,1,'save/build POST must never be retried automatically');
fetches=0;await assert.rejects(()=>localRequest('/api/job?id=private',undefined,'private-token'),error=>error.message.includes('GET /api/job')&&!error.message.includes('private'));
assert.equal(fetches,2);
globalThis.fetch=async()=>{throw new DOMException('Stopped','AbortError');};
await assert.rejects(()=>localRequest('/api/check',{},'token'),e=>e.name==='AbortError');
console.log('Preview requests: latest-only debounce, in-flight cancellation, safe GET retry, English route context and no POST retries passed.');
